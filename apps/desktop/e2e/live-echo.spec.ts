import { expect, test, type Page } from '@playwright/test';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { withM1Stack } from './support/m1-stack';

type Stack = Parameters<Parameters<typeof withM1Stack>[1]>[0];

/** The live reducer the panel runs, reached through the URL Vite serves it on. */
type LiveModule = {
  EMPTY_TRANSCRIPT: unknown;
  applyLiveEvent: (state: unknown, name: string, data: unknown) => { rows: { key: string }[] };
};

const desktop = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const repository = resolve(desktop, '..', '..');
const ECHO_SCRIPT = resolve(repository, 'fixtures/audio/echo-live.transcript.json');
// Generated by the agent from that same script on its first session, kept out of the repository.
const ECHO_WAV = join(tmpdir(), `interline-e2e-echo-live-${process.pid}.wav`);
const ECHO_TEXT = 'Il faut relancer le serveur avant la reunion.';
const SOLO_TEXT = 'Je vais envoyer le compte rendu ce soir.';

async function openDesktop(page: Page, stack: Stack) {
  expect(stack.coreReady, stack.diagnostics()).toBe(true);
  expect(stack.viteReady, stack.diagnostics()).toBe(true);
  await page.goto('/');
  await expect(page.getByRole('heading', { name: 'Interline', exact: true })).toBeVisible();
  await expect(page.getByRole('button', { name: 'Record', exact: true })).toBeEnabled();
}

test('AC5_suppressedRowRemovedAndNeverReadded', async ({ page }, info) => {
  await withM1Stack(
    { agentArgs: ['--speed=1', `--wav=${ECHO_WAV}`, `--script=${ECHO_SCRIPT}`] },
    async (stack) => {
      await openDesktop(page, stack);
      await page.getByRole('button', { name: 'Record', exact: true }).click();
      await expect(page.getByRole('status')).toHaveText('recording');

      const transcript = page.getByRole('list', { name: 'Transcript', exact: true });
      const echoRows = transcript.getByRole('listitem').filter({ hasText: ECHO_TEXT });
      const soloRows = transcript.getByRole('listitem').filter({ hasText: SOLO_TEXT });

      // The unpaired mic final is scripted at 13 s, so both echo pairs are already decided when it appears.
      await expect(soloRows).toHaveText([/^Me\b/], { timeout: 30_000 });
      // The microphone row that repeated the system final is gone; only the remote row carries that text.
      await expect(echoRows).toHaveText([/^Them\b/]);

      // Nothing brings the suppressed key back: it is absent three seconds later too.
      await page.waitForTimeout(3_000);
      await expect(echoRows).toHaveText([/^Them\b/]);
      await expect(soloRows).toHaveText([/^Me\b/]);

      // The re-add rule cannot come from the agent (no event replays a key after suppression), so drive the real
      // reducer the panel uses: a later partial and final on the same key must stay ignored.
      const reduction = await page.evaluate(async (source: string) => {
        const liveState = (await import(/* @vite-ignore */ source)) as LiveModule;
        const mic = { stream: 'mic', seg: 'm-echo-9', speaker: 'Me', text: 'Doublon', rev: 7 };
        let state = liveState.applyLiveEvent(liveState.EMPTY_TRANSCRIPT, 'stt.final', mic);
        const before = state.rows.length;
        state = liveState.applyLiveEvent(state, 'transcript.suppressed', {
          meetingId: 'm', stream: 'mic', seg: 'm-echo-9',
        });
        const after = state.rows.length;
        state = liveState.applyLiveEvent(state, 'stt.partial', {
          stream: 'mic', seg: 'm-echo-9', speaker: 'Me', text: 'Dou', rev: 9,
        });
        state = liveState.applyLiveEvent(state, 'stt.final', mic);
        state = liveState.applyLiveEvent(state, 'stt.final', {
          stream: 'system', seg: 's-echo-9', speaker: 'Them', text: 'Doublon', rev: 0,
        });
        return { before, after, keys: state.rows.map((row) => row.key) };
      }, '/src/liveState.ts');

      expect(reduction.before, 'the final adds the microphone row').toBe(1);
      expect(reduction.after, 'transcript.suppressed removes that row').toBe(0);
      expect(reduction.keys, 'a later partial and final cannot bring the suppressed key back')
        .toEqual(['system:s-echo-9']);
    },
    async (body) => { await info.attach('m1-stack', { body, contentType: 'text/plain' }); },
  );
});
